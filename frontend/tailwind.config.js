/**
 * ⚠️ 这里的颜色**不是随手挑的**，每个值都经过 WCAG 2.1 实测
 * （脚本 `tools/contrast.mjs`，改色值后必须重跑）。改之前先读下面的分层约定。
 *
 * ── 两套色，两种职责，不要混用 ────────────────────────────────────────
 *   1. `surface` / `slate`（**表面**）—— 底色与描边，表达「这块在界面里的层级」。
 *   2. `ink` / `brand` / 红绿琥珀（**语义**）—— 文字与状态，表达「这是什么意思」。
 *
 * ── 表面阶梯：四层，靠**亮度差**建立层级 ──────────────────────────────
 * 历史缺陷：内嵌块曾用 7 档几乎同色的灰，亮度差只有 2~4%，人眼分辨不出，
 * 结果「所有块看起来一样重」，界面没有落点。这不是审美问题，是**机械性缺陷**。
 * 现在收敛为四层，相邻层相对亮度差 37%~70%：
 *
 *   canvas   页面底       #05070e
 *   panel    主面板       #0d1424   与 canvas 差 69.7%
 *   inset    面板内分区   #141d30   与 panel  差 42.5%
 *   raised   芯片/输入框  #1b2640   与 inset  差 37.6%
 *
 * ── 描边三分 ──────────────────────────────────────────────────────────
 *   line        装饰性描边（卡片外框）。纯装饰不受 WCAG 约束，1.49~1.78:1 足够。
 *   line-soft   表内分隔线，比 line 更弱，避免表格看起来像格子墙。
 *   line-strong 交互元素描边（输入框 / 描边按钮）—— **它就是这个控件唯一的边界
 *               标识**，按 WCAG 1.4.11 需 >= 3:1。实测 4.23 / 3.86 / 3.54。
 *               反面：别用 line / slate-700 描输入框（1.4~1.7:1，等于看不见框）。
 */

/**
 * `slate-*` 在本项目里**历史上就是**表面阶梯（bg-slate-900 = 主卡、
 * bg-slate-800/70 = 子块、border-slate-800 = 外框），只是当年选的 900/800
 * 两档只差 2~4% 亮度，层级糊成一片。
 *
 * 所以把最深的四档**重定向**到实测过的新阶梯：全站存量标记不改一个字就整体
 * 落到新层级上，避免出现「一半新一半旧」的过渡态（那比不改更难看）。
 * 浅档（100~600）保持 Tailwind 原值 —— 它们是文字色与交互描边，
 * 已由 `ink` / `line-strong` 接管，实测数记在 src/lib/ui.ts。
 */
const SLATE = {
  50: "#f8fafc",
  100: "#f1f5f9",
  200: "#e2e8f0",
  300: "#cbd5e1",
  400: "#94a3b8",
  500: "#64748b",
  600: "#475569",
  // ↓ 以下四档是覆盖值，语义见上方「表面阶梯」
  700: "#2b3a5a", // line
  800: "#141d30", // inset
  900: "#0d1424", // panel
  950: "#05070e", // canvas
};

export default {
  content: ["./index.html", "./src/**/*.{js,ts,jsx,tsx}"],
  theme: {
    extend: {
      colors: {
        slate: SLATE,

        /**
         * 语义表面阶梯。**新代码一律用这套名字** —— 语义比色值稳，
         * 将来换肤只动这一个映射，不用全站 grep 色号。
         */
        surface: {
          canvas: SLATE[950],
          panel: SLATE[900],
          inset: SLATE[800],
          raised: "#1b2640",
          line: SLATE[700],
          "line-soft": "#1a2438",
          "line-strong": SLATE[500],
        },

        /**
         * 主色（结构色 / 填充色）。
         *
         * ⚠️ `brand` #2563eb **只能当填充** —— 按钮底、激活底、图标底、进度条。
         * 不要当暗底上的文字色：实测在 panel / inset / raised 上只有
         * 3.56 / 3.18 / 2.76:1，全低于 AA 正文 4.5:1。
         * 暗底上的品牌色文字用 `brand-light`（7.23:1）；焦点环同理。
         *
         * 必须与红/绿保持距离 —— 红绿已被行情语义独占（见 src/lib/tone.ts）。
         */
        brand: {
          DEFAULT: "#2563eb",
          /** 主按钮 hover 底。 */
          dark: "#1d4ed8",
          /** 暗底上的品牌色**文字** / 焦点环。white on brand = 5.17:1。 */
          light: "#60a5fa",
          /** 需要比 light 更强调的品牌色文字。 */
          soft: "#93c5fd",
        },

        /**
         * 文字色阶梯（暗色主题专用）。
         *
         * 五档全部在**四层表面**上实测 >= 4.5:1，所以任意层级组合都安全 ——
         * 组件不必知道自己被放在了哪一层上。改表面色或改这五个值都要重跑实测。
         *
         *   ink-faint   #8fa0b8   canvas 7.56 / panel 6.90 / inset 6.32 / raised 5.64
         *   ink-muted   #94a3b8   7.85 / 7.17 / 6.56 / 5.86   标签、表头
         *   ink-soft    #cbd5e1  13.56 / 12.38 / 11.33 / 10.12  正文
         *   ink         #e2e8f0  16.33 / 14.91 / 13.65 / 12.19  标题
         *   ink-strong  #f8fafc  19.24 / 17.57 / 16.08 / 14.36  页面级标题、大数字
         *
         * 反面：不要再用 `text-slate-500` / `text-slate-600` 当文字色 ——
         * 实测只有 3.07 / 1.93:1，暗底上读不清。它们的旧位置已迁到 `ink-faint`。
         */
        ink: {
          strong: "#f8fafc",
          DEFAULT: "#e2e8f0",
          soft: "#cbd5e1",
          muted: "#94a3b8",
          faint: "#8fa0b8",
        },
      },
    },
  },
  plugins: [],
};
